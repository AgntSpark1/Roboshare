// Copies ABIs from the Foundry build (contracts/out) into src/abi.ts.
// Run `forge build` in contracts/ first. The output is committed so apps need no Foundry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const contracts = [
  "IdentityRegistry",
  "AssetRegistry",
  "AuditRegistry",
  "SubscriptionRouter",
  "ProjectFactory",
  "RwaShareToken",
  "OfferingManager",
  "RevenueDistributor",
  "ReferralRewards",
  "ShareMarket",
  "ProjectActivator",
];
let out = "// GENERATED by scripts/gen-abi.mjs from contracts/out. Do not edit.\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "packages/shared/src/abi.ts"), out);
console.log(`wrote ${contracts.length} ABIs`);
